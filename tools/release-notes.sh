#!/usr/bin/env bash
# Описание релиза на русском: что скачать и как установить. Перечисляет только то, что уже собрано.
#   bash tools/release-notes.sh <тег релиза>
set -euo pipefail
TAG="$1"
REPO="${GITHUB_REPOSITORY:-uproxe/NetLoom}"
# черновики не видны по адресу …/releases/tags/<тег>, поэтому ищем в общем списке
ASSETS="$(gh api "repos/$REPO/releases?per_page=100" --jq ".[] | select(.tag_name == \"$TAG\") | .assets[] | \"\\(.name)\\t\\(.label)\\t\\(.size)\"")"
has() { grep -Eq "^$1	" <<<"$ASSETS"; }
size() { awk -F'\t' -v n="$1" '$1 == n { printf "%.0f МБ", $3 / 1048576 }' <<<"$ASSETS"; }
engine() { awk -F'\t' -v n="$1" '$1 == n { print $2 }' <<<"$ASSETS" | sed -n 's/.*движок \([0-9.]*\).*/\1/p'; }
link() { echo "https://github.com/$REPO/releases/download/$TAG/$1"; }
VER="${TAG#v}"

WIN="NetLoom-$VER-windows-x64-setup.exe"; WINZIP="NetLoom-$VER-windows-x64.zip"
DEB="netloom_${VER}_amd64.deb"; DMG="NetLoom-$VER-macos-universal.dmg"
RPM="netloom-$VER-1.x86_64.rpm"; ARCHPKG="netloom-$VER-1-x86_64.pkg.tar.zst"; APPIMAGE="NetLoom-$VER-x86_64.AppImage"
APK="NetLoom-$VER-android-arm64.apk"; APK32="NetLoom-$VER-android-arm32.apk"
EV=""
for f in "$WIN" "$DEB" "$DMG"; do [ -n "$EV" ] || EV="$(engine "$f")"; done

cat <<TXT
Приватный браузер со своим интерфейсом, встроенной блокировкой рекламы и VPN.
Без аккаунтов и телеметрии.${EV:+ Движок Gecko ESR $EV.}
TXT
if [ "$VER" = "1.0.4" ]; then cat <<'TXT'

## Что нового в 1.0.4

- **Пакеты для других Linux.** Кроме .deb теперь есть .rpm для Fedora, РЕД ОС, РОСА и openSUSE,
  пакет для Arch и Manjaro и AppImage, который запускается на любом дистрибутиве без установки.
  Каждый пакет перед выпуском ставится в настоящий дистрибутив и проверяется запуском.
TXT
fi
if [ "$VER" = "1.0.3" ]; then cat <<'TXT'

## Что нового в 1.0.3

- **Удаление стирает все данные.** В Windows удаление NetLoom теперь убирает закладки, пароли, историю,
  VPN-серверы и настройки — после новой установки ничего старого не появится. Обновление их по-прежнему не трогает.
- **Расширения устанавливать нельзя.** Блокировка рекламы и VPN уже встроены, а чужие расширения могут следить за вами.
- **Пункт «Видео в отдельном окне» убран из меню.** Сама функция осталась: значок на видео, кнопка в адресной строке
  или Ctrl+Shift+] (на Mac ⌘⌥⇧]).
TXT
fi
if [ "$VER" = "1.0.2" ]; then cat <<'TXT'

## Что нового в 1.0.2

- **Больше никакой лисы.** На страницах ошибок, в пустом списке паролей и в окне «Защита сайта» (замок в адресной строке)
  теперь значки NetLoom. Из списка паролей убраны инструкции про синхронизацию и учётную запись — их в NetLoom нет.
- **Мастер-пароль.** Настройки показывали «Не задан», даже когда пароль был задан. Исправлено. Из-за той же ошибки
  не появлялось предложение задать мастер-пароль при запуске — теперь оно есть, пока пароль не задан.
- **Убрана кнопка «Добавить вкладку на панель задач»** в адресной строке (Windows).
TXT
fi
if [ "$VER" = "1.0.1" ]; then cat <<'TXT'

## Что нового в 1.0.1

- **Намного быстрее и легче.** Блокировщик рекламы переписан: он занимает в 10 раз меньше памяти,
  а правила скрытия рекламы подключаются только для открытого сайта. На замере с восемью тяжёлыми
  сайтами процессор загружен в 6 раз меньше, чем в 1.0.0, а в простое — меньше 10 % вместо 245 %.
  Памяти уходит на 750 МБ меньше. Это даже легче чистого движка без NetLoom: рекламу не нужно загружать.
- **Адресная строка без подсказок.** Браузер ничего не предлагает и не отправляет набранный текст, пока вы не нажмёте Enter.
- **Видео в отдельном окне.** Значок на видео, кнопка в адресной строке или пункт меню «Видео в отдельном окне».
  На Android видео во весь экран само уходит в маленькое окно, если выйти из приложения.
- **Значок на Mac** теперь такого же размера, как у остальных программ.
- Исправлена проверка скорости серверов VPN, убраны фоновые службы движка, которые зря тратили процессор.
TXT
fi
cat <<TXT

## Скачать

| Система | Файл | Размер |
|---|---|---|
TXT
has "$WIN"    && echo "| Windows 10 и 11 (64 бит) | [Установщик]($(link "$WIN")) | $(size "$WIN") |"
has "$WINZIP" && echo "| Windows без установки | [Архив .zip]($(link "$WINZIP")) | $(size "$WINZIP") |"
has "$DEB"    && echo "| Linux: Ubuntu, Debian, Mint, Astra, elementary OS | [Пакет .deb]($(link "$DEB")) | $(size "$DEB") |"
has "$RPM"    && echo "| Linux: Fedora, РЕД ОС, РОСА, openSUSE | [Пакет .rpm]($(link "$RPM")) | $(size "$RPM") |"
has "$ARCHPKG" && echo "| Linux: Arch, Manjaro, EndeavourOS | [Пакет .pkg.tar.zst]($(link "$ARCHPKG")) | $(size "$ARCHPKG") |"
has "$APPIMAGE" && echo "| Linux: любой дистрибутив, без установки | [AppImage]($(link "$APPIMAGE")) | $(size "$APPIMAGE") |"
has "$DMG"    && echo "| macOS 10.15 и новее (Apple M1–M4 и Intel) | [Образ .dmg]($(link "$DMG")) | $(size "$DMG") |"
has "$APK"    && echo "| Android 8 и новее (64 бит) | [Приложение .apk]($(link "$APK")) | $(size "$APK") |"
has "$APK32"  && echo "| Android, старые 32-битные телефоны | [Приложение .apk]($(link "$APK32")) | $(size "$APK32") |"

cat <<'TXT'

## Как установить

**Windows.** Запустите установщик — права администратора не нужны. Если Windows
покажет окно «Система Windows защитила ваш компьютер», нажмите «Подробнее» →
«Выполнить в любом случае» (у NetLoom пока нет платной цифровой подписи).
Чтобы сделать NetLoom браузером по умолчанию: «Настройки» NetLoom → «Основное».

**Linux.** Выберите файл под свой дистрибутив и откройте его двойным щелчком (Центр приложений)
или поставьте в терминале:
- Ubuntu, Debian, Mint, Astra, elementary OS: `sudo apt install ./netloom_*_amd64.deb`
- Fedora, РЕД ОС, РОСА: `sudo dnf install ./netloom-*.x86_64.rpm`
- openSUSE: `sudo zypper install --allow-unsigned-rpm ./netloom-*.x86_64.rpm`
- Arch, Manjaro, EndeavourOS: `sudo pacman -U ./netloom-*-x86_64.pkg.tar.zst`
- любой другой: скачайте AppImage, в свойствах файла разрешите запуск (или `chmod +x NetLoom-*.AppImage`)
  и откройте его. Ставить ничего не нужно, но в меню программ он сам не появится.

**macOS.** Откройте образ и перетащите NetLoom в «Программы». При первом запуске
macOS предупредит, что не может проверить программу (у NetLoom нет платного
сертификата Apple): откройте «Системные настройки» → «Конфиденциальность и
безопасность» → «Всё равно открыть». Это нужно один раз. Подробнее — в файле
README.txt внутри образа.

**Android.** Скачайте файл .apk на телефон и откройте его. Телефон попросит
разрешить установку из этого источника — разрешите.

## Что внутри

- Блокировка рекламы и счётчиков: базы AdGuard и EasyList, включая русские.
- VPN и прокси: VLESS, VMess, Trojan, Shadowsocks, Hysteria2, TUIC, WireGuard,
  AnyTLS, SSH, SOCKS5, HTTP, подписки. Российские сайты можно открывать напрямую,
  для любого сайта можно выбрать: через VPN или напрямую.
- Защита от опасных сайтов без Google: списки проверяются на самом устройстве,
  адреса никуда не отправляются.
- Главный пароль для сохранённых паролей, импорт закладок из Яндекс Браузера,
  Chrome, Safari и Firefox, экспорт закладок и паролей.
- Обновляется только движок — исправлениями безопасности.
TXT
